#!/usr/bin/env node
/**
 * Build a drop-in bundle for Hostinger.
 *
 * The GitHub Pages build is not portable: it serves from a subfolder, so every
 * link carries a /YBE-Auto-Repair-Center prefix and every canonical points at
 * github.io. Uploaded to a domain root as-is, every link and asset 404s and
 * Google keeps indexing the GitHub copy. This rebuilds at the root with the
 * real domain, adds server config Apache/LiteSpeed needs, and zips the result.
 *
 *   npm run build:hostinger
 *   SITE_DOMAIN=example.com npm run build:hostinger
 *
 * Output: dist-hostinger/ and dist-hostinger.zip
 */

const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = path.join(__dirname, '..');
const DOMAIN = process.env.SITE_DOMAIN || 'pgcountyautorepair.com';
const OUT_DIR = 'dist-hostinger';
const OUT = path.join(ROOT, OUT_DIR);
const SITE_URL = `https://${DOMAIN}`;

console.log(`\nBuilding for ${SITE_URL}\n`);

fs.rmSync(OUT, { recursive: true, force: true });

execFileSync('node', [path.join(ROOT, 'build.js')], {
  cwd: ROOT,
  stdio: 'inherit',
  env: {
    ...process.env,
    SITE_URL,
    BASE_PATH: '',          // root-served: no prefix
    OUT_DIR,
    SKIP_ROOT_PUBLISH: '1'  // never rewrite the repo root for another host
  }
});

/*
 * Server config. Hostinger runs LiteSpeed, which reads .htaccess.
 *
 * The service-worker rule is the one that bites: sw.js must never be cached by
 * the browser, or a visitor keeps running an old worker that serves an old
 * cached site, and no amount of redeploying reaches them.
 */
const htaccess = `# YBE Auto Repair Center
# Generated by scripts/build-hostinger.js — edit that, not this file.

DirectoryIndex index.html
ErrorDocument 404 /404.html

<IfModule mod_rewrite.c>
  RewriteEngine On

  # Canonical host: https, no www. One address, one set of rankings.
  RewriteCond %{HTTPS} !=on
  RewriteRule ^(.*)$ https://${DOMAIN}/$1 [R=301,L]

  RewriteCond %{HTTP_HOST} ^www\\.${DOMAIN.replace(/\./g, '\\.')}$ [NC]
  RewriteRule ^(.*)$ https://${DOMAIN}/$1 [R=301,L]

  # Pretty URLs: /services/ is served by /services/index.html already, but a
  # request without the trailing slash should not 404.
  RewriteCond %{REQUEST_FILENAME} !-f
  RewriteCond %{REQUEST_FILENAME} !-d
  RewriteCond %{REQUEST_FILENAME}/index.html -f
  RewriteRule ^(.*)$ /$1/ [R=301,L]
</IfModule>

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css text/plain text/xml \\
    application/javascript application/json application/xml \\
    application/manifest+json image/svg+xml
</IfModule>

<IfModule mod_expires.c>
  ExpiresActive On

  # Content-hashed and stable assets can be cached hard.
  ExpiresByType text/css                  "access plus 1 year"
  ExpiresByType application/javascript    "access plus 1 year"
  ExpiresByType image/jpeg                "access plus 1 year"
  ExpiresByType image/png                 "access plus 1 year"
  ExpiresByType image/webp                "access plus 1 year"
  ExpiresByType image/svg+xml             "access plus 1 year"
  ExpiresByType font/woff2                "access plus 1 year"

  # HTML changes with every deploy; revalidate it.
  ExpiresByType text/html                 "access plus 0 seconds"
</IfModule>

# The service worker must always be revalidated, or an old worker keeps
# serving an old cached site and redeploys never reach the visitor.
<FilesMatch "sw\\.js$">
  <IfModule mod_headers.c>
    Header set Cache-Control "no-cache, no-store, must-revalidate"
  </IfModule>
</FilesMatch>

<IfModule mod_headers.c>
  Header set X-Content-Type-Options "nosniff"
  Header set Referrer-Policy "strict-origin-when-cross-origin"
</IfModule>

AddType application/manifest+json .webmanifest
`;

fs.writeFileSync(path.join(OUT, '.htaccess'), htaccess);

// Zip it so it can be dropped straight into hPanel's File Manager.
const zipPath = path.join(ROOT, `${OUT_DIR}.zip`);
fs.rmSync(zipPath, { force: true });
execFileSync('zip', ['-r', '-q', zipPath, '.'], { cwd: OUT });

const count = (dir) =>
  fs.readdirSync(dir, { withFileTypes: true }).reduce(
    (n, e) => n + (e.isDirectory() ? count(path.join(dir, e.name)) : 1),
    0
  );

console.log(`  ✓ .htaccess written (https, no-www, compression, caching)`);
console.log(`  ✓ ${count(OUT)} files in ${OUT_DIR}/`);
console.log(`  ✓ ${OUT_DIR}.zip  (${(fs.statSync(zipPath).size / 1024 / 1024).toFixed(1)} MB)\n`);
console.log(`Upload the CONTENTS of the zip into public_html/ on ${DOMAIN}.\n`);
